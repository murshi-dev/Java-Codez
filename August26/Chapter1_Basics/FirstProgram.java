package src;

public class FirstProgram {

	public static void main(String[] args) {

		//println --moves cursor to the next line
		System.out.println("Hello World");
		// \n --moves content to next line
		System.out.println("First Class\n in Programming");
		// \t --provides a tab space
		System.out.println("1.Install JDK\t2.Install Eclipse");
		//print --prints in the same line
		System.out.print("Java");
		System.out.print("Programming");
	}
}



